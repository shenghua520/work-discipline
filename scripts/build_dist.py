GENERATORS = {
    "install-tree": gen_install_tree,
    "bash-download": gen_bash_download,
    "ps-download": gen_ps_download,
    "repo-tree": gen_repo_tree,
}
README_FILES = [("README.md", "cn"), ("README.en.md", "en")]


def render_blocks(lang):
    return {key: fn(lang) for key, fn in GENERATORS.items()}


def markers_of(text, key):
    """某 key 的 BEGIN/END 标记出现次数（不看配对——孤儿标记也要抓）。"""
    return (len(re.findall(r"BEGIN GENERATED:" + re.escape(key), text)),
            len(re.findall(r"END GENERATED:" + re.escape(key), text)))


BLOCK_RE = lambda key: re.compile(
    r"(^[ \t]*<!-- BEGIN GENERATED:" + re.escape(key) + r" -->[ \t]*\n)(.*?)(\n[ \t]*<!-- END GENERATED:" + re.escape(key) + r" -->[ \t]*$)",
    re.S | re.M)


def doc_blocks_status():
    """校验 README 生成块：标记计数恰好 1/1、内容逐字一致、渲染内容只出现一次。"""
    problems = []
    for filename, lang in README_FILES:
        path = os.path.join(ROOT, filename)
        if not os.path.exists(path):
            problems.append(f"{filename} 缺失")
            continue
        text = read(path)
        expected = render_blocks(lang)
        for key, want in expected.items():
            nb, ne = markers_of(text, key)
            if nb != 1 or ne != 1:
                problems.append(f"{filename} 标记计数异常 {key}: BEGIN={nb} END={ne}（各须为 1）")
                continue
            m = BLOCK_RE(key).search(text)
            if not m:
                problems.append(f"{filename} 缺生成标记 {key}")
            elif m.group(2) != want:
                problems.append(f"{filename} 生成块 {key} 不同步")
            # 幂等/唯一性：同一 key 的渲染内容全篇只允许出现一次
            if text.count(want) != 1:
                problems.append(f"{filename} 生成块 {key} 内容出现 {text.count(want)} 次（应为 1）")
        # VERSION 联动：变更记录首条 vN 必须等于 VERSION 的主版本
        title = "## 变更记录" if lang == "cn" else "## Changelog"
        changelog = text.split(title, 1)
        if len(changelog) > 1:
            first = next((l for l in changelog[1].split("\n") if l.startswith("- **v")), "")
            vm = re.match(r"- \*\*v(\d+)\b", first)
            want_v = "v" + VERSION.split(".")[0]
            if vm and vm.group(1) != want_v[1:]:
                problems.append(f"{filename} 变更记录首条 v{vm.group(1)} 与 VERSION {VERSION} 不一致（应 {want_v}）")
    return problems


def regenerate_readme_blocks():
    """回填生成块。修复带删除语义：任何异常状态先清场，再在原位置重建一个新块。

    绝不在文件末尾追加孤儿——那会把坏状态写成合法基准。
    """
    for filename, lang in README_FILES:
        path = os.path.join(ROOT, filename)
        if not os.path.exists(path):
            continue
        text = read(path)
        local_inserted = []
        for key, want in render_blocks(lang).items():
            pattern = BLOCK_RE(key)
            m = pattern.search(text)
            nb, ne = markers_of(text, key)
            # 健康块：直接回填内容
            if nb == 1 and ne == 1 and m:
                text = pattern.sub(lambda x: x.group(1) + want + x.group(3), text, count=1)
                continue
            # 异常：清场——删除该 key 的一切残骸（所有标记 + 所有渲染内容副本），
            # 在最早出现处重建一个规范块。删完必须"内容出现 0 次"，否则幂等断言会失败。
            positions = [x.start() for x in re.finditer(
                r"<!-- (?:BEGIN|END) GENERATED:" + re.escape(key) + r" -->", text)]
            # 落点优先用块自己的最早标记位置；整块缺失时退回"该 key 的归属章节"末尾，
            # 绝不 append 到文件末尾（v9 那个 bug：安装树被贴到变更记录之后）。
            if positions:
                anchor = min(positions)
            else:
                section = ("## 安装与恢复" if lang == "cn" else "## Installation and recovery") \
                    if key in ("install-tree", "bash-download", "ps-download") else \
                          ("## 仓库结构" if lang == "cn" else "## Repository layout")
                si = text.find(section)
                if si < 0:
                    raise SystemExit(f"找不到落点章节 {section}（{filename}/{key}）")
                nxt = text.find("\n## ", si + len(section))
                anchor = nxt + 1 if nxt >= 0 else len(text)
                # 锚点落在下一个章节标题之前，若该处是空行则往前收到非空内容后
                while anchor > si and text[anchor - 1] in "\n\r":
                    anchor -= 1
            spans = [(x.start(), x.end()) for x in re.finditer(
                r"<!-- (?:BEGIN|END) GENERATED:" + re.escape(key) + r" -->", text)]
            # 渲染内容本身的所有出现（孤儿正文就是没有标记包裹的那份）——一起清掉
            starts = []
            pos = 0
            while True:
                k = text.find(want, pos)
                if k < 0:
                    break
                starts.append((k, k + len(want)))
                pos = k + 1
            spans.extend(starts)
            for s, e in sorted(set(spans), reverse=True):
                text = text[:s] + text[e:]
            block = (f"\n<!-- BEGIN GENERATED:{key} -->\n{want}\n"
                     f"<!-- END GENERATED:{key} -->\n")
            anchor = min(anchor, len(text))
            # 保证标记独占一行：锚点前若非行首则补换行，锚点后若是正文则也补换行
            left = text[:anchor]
            if left and not left.endswith("\n"):
                left += "\n"
            text = left + block + text[anchor:]
            local_inserted.append(key)
        write(path, text)
        print(f"  回填 {filename} 的 {len(GENERATORS)} 个生成块"
              + (f"（清场重建 {local_inserted}）" if local_inserted else ""))
    return True


def tracked_files():
    out = []
    for root, dirs, names in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d != ".git"]
        for name in names:
            full = os.path.join(root, name)
            rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
            if rel == "manifest.json" or rel.startswith(".git/") or rel.startswith("dist/"):
                continue
            if rel in ("SKILL.md", "SKILL.en.md") or rel.startswith("references/"):
                rel = "skills/work-discipline/" + rel
            out.append(rel)
    return sorted(out)


def disk_path(repo_rel):
    direct = os.path.join(ROOT, repo_rel)
    if os.path.exists(direct):
        return direct
    prefix = "skills/work-discipline/"
    if repo_rel.startswith(prefix):
        return os.path.join(ROOT, repo_rel[len(prefix):])
    return direct


def expected_manifest(cn_flat, en_flat):
    files = {}
    for rel in tracked_files():
        full = disk_path(rel)
        files[rel] = {"sha256": sha256(full), "size": os.path.getsize(full)}
    files["dist/work-discipline.flat.md"] = {
        "sha256": hashlib.sha256(cn_flat.encode("utf-8")).hexdigest(),
        "size": len(cn_flat.encode("utf-8")),
    }
    files["dist/work-discipline.flat.en.md"] = {
        "sha256": hashlib.sha256(en_flat.encode("utf-8")).hexdigest(),
        "size": len(en_flat.encode("utf-8")),
    }
    return {
        "version": VERSION,
        "schema": "sha256+size; verify with sha256sum / certutil / Get-FileHash, no Python needed",
        "note": "manifest.json itself is intentionally excluded to avoid a self-reference cycle.",
        "files": files,
    }


def main():
    check_only = "--check" in sys.argv
    cn_flat = build_flat(HEADER_CN, "SKILL.md", REFS_CN)
    en_flat = build_flat(HEADER_EN, "SKILL.en.md", REFS_EN)

    problems = []
    for rel, content in [("dist/work-discipline.flat.md", cn_flat),
                         ("dist/work-discipline.flat.en.md", en_flat)]:
        full = os.path.join(ROOT, rel)
        if not os.path.exists(full):
            problems.append(f"缺失 {rel}")
        elif read(full) != content:
            problems.append(f"不同步 {rel}（源文件已改但未重新生成）")

    problems.extend(doc_blocks_status())
    expected = expected_manifest(cn_flat, en_flat)

    if os.path.exists(MANIFEST):
        try:
            actual = json.loads(read(MANIFEST))
        except Exception as exc:
            problems.append(f"manifest.json 解析失败: {exc}")
            actual = {}
        for rel, meta in expected["files"].items():
            got = actual.get("files", {}).get(rel)
            if not got or got.get("sha256") != meta["sha256"]:
                problems.append(f"manifest 哈希不符或缺失: {rel}")
        extra = set(actual.get("files", {})) - set(expected["files"])
        if extra:
            problems.append(f"manifest 含多余条目: {sorted(extra)}")
        if actual.get("version") != VERSION:
            problems.append(f"manifest 版本不符: 实际 {actual.get('version')} 期望 {VERSION}")
    else:
        problems.append("缺失 manifest.json")

    if check_only:
        if problems:
            for p in problems:
                print(f"  DIFF {p}")
            print(f"FAIL: {len(problems)} 项不同步")
            sys.exit(1)
        print(f"PASS: 扁平版 / manifest / README 生成块均与源同步（{len(expected['files'])} 个文件）")
        return

    if problems:
        print("生成中发现问题（将按源重建）:")
        for p in problems:
            print("  ", p)

    # 顺序：先回填 README（会改 README 哈希），再自复查所有块真正落位，最后算 manifest。
    # 生成器绝不能对"块没补齐"报 PASS —— 那是写路径上的伪绿。
    regenerate_readme_blocks()
    residual = doc_blocks_status()
    if residual:
        for p in residual:
            print(f"  FAIL {p}")
        print("FAIL: 回填后仍有生成块未落位，拒绝报生成成功")
        sys.exit(1)
    expected = expected_manifest(cn_flat, en_flat)

    os.makedirs(DIST, exist_ok=True)
    for rel, content in [("dist/work-discipline.flat.md", cn_flat),
                         ("dist/work-discipline.flat.en.md", en_flat)]:
        write(os.path.join(ROOT, rel), content)
        print(f"  写入 {rel}  {len(content.encode('utf-8'))} B")
    write(MANIFEST, json.dumps(expected, ensure_ascii=False, indent=2, sort_keys=True) + "\n")
    print(f"  写入 manifest.json  {len(expected['files'])} 个文件")
    print("PASS: 生成完成")


